global.style = async function styles(text, styleNum) {
    let replacer = []
    xStr.map((v, i) => replacer.push({
        original: v,
        convert: yStr[styleNum][i]
    }))
    return text.toLowerCase().split("").map(v => {
        const r = replacer.find(x => x.original === v)
        return r ? r.convert : v
    }).join("")
}

async function handler(m, { conn, text, command, usedPrefix }) {
    if (!text) {
        let info = `❀ يـرجـى إدخـال الـنـص الـذي تـريـد زخـرفـتـه.\n> *مثال: ${usedPrefix + command} Text*`
        return conn.reply(m.chat, info, fkontak, rcanal)
    }

    await m.react('🕒')

    let cards = []
    let totalStyles = Object.keys(yStr).length

    for (let i = 1; i <= totalStyles; i++) {
        let decorated = await global.style(text, i)
        
        cards.push({
            header: {
                title: `*✨ نـمـط الـزخـرفـة رقم (${i}/${totalStyles})*`
            },
            body: {
                text: `📝 الـنـص الأصـلي: ${text}\n\n🎨 الـنـص الـمـزخـرف:\n\`${decorated}\``
            },
            nativeFlowMessage: {
                buttons: [
                    {
                        name: "cta_copy",
                        buttonParamsJson: JSON.stringify({
                            display_text: "📋 نـسـخ الـزخـرفـة",
                            copy_code: decorated
                        })
                    }
                ]
            }
        })
    }

    let msg = {
        viewOnceMessage: {
            message: {
                interactiveMessage: {
                    header: {
                        title: `*🎨 لـوِحـة زخـرفـة الـنـصـوص*`,
                        hasMediaAttachment: false
                    },
                    body: {
                        text: `إليك النص مزخرفاً بأنماط مختلفة، اسحب يميناً أو يساراً للاطلاع عليها وانقر على زر النسخ أسفل أي نمط:`
                    },
                    carouselMessage: {
                        cards: cards
                    }
                }
            }
        }
    }

    await m.react('✅')
    return await conn.relayMessage(m.chat, msg, {})
}

handler.help = ['خط <نص>']

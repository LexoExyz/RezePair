let handler = async (m, { conn }) => {
    // التحقق إذا كان في مجموعة
    if (!m.isGroup) {
        let info = `🚫 هذا الأمر يعمل فقط في *المجموعات*!`
        return conn.reply(m.chat, info, fkontak, rcanal)
    }

    await m.react('💡')
    const randomQuote = adviceQuotes[Math.floor(Math.random() * adviceQuotes.length)];

    let info = `*💡 نصيحة لك يا @${m.sender.split('@')[0]} :*\n`
    info += `*‏⎔ ٠ ┈─ ━╼ • ◞💎◜ • ╾━ ─┈‏ ٠ ⎔*\n`
    info += `「 ${randomQuote} 」\n`
    info += `*⎔ ┈───┈ ⊱🕊️⊰ ┈───┈ ⎔*\n`

    // إرسال النصيحة مباشرة مع المنشن ومظهر القناة دون رسالة مكررة
    return await conn.sendMessage(m.chat, { 
        text: info, 
        mentions: [m.sender],
        contextInfo: typeof rcanal !== 'undefined' ? rcanal.contextInfo : undefined
    }, { quoted: m });
}

handler.help = ['نصيحة']
handler.tags = ['الـأعـضـاء']
handler.command = ['نصيحة', 'نصيحه']

export default handler
